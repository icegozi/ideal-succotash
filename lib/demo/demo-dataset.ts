/**
 * Returns a date string (YYYY-MM-DD) shifted relative to today.
 * Ensures demo data is always relative and never goes stale.
 */
export function daysFromNow(days: number): string {
  const d = new Date();
  d.setDate(d.getDate() + days);
  return d.toISOString().split("T")[0];
}

